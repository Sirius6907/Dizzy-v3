/// Phase 5 — 5x7 dot-matrix LED text/status display.
///
/// Draws each character as dots from a compact 5x7 font — no [Text]
/// widget involved. OLED dark: [DizzyVoid.obsidian] background, lit
/// dots in [litColor], unlit dots barely visible.
class DizzyDotMatrix extends StatelessWidget {
  final String text;
  final Color litColor;
  final double dotSize;
  final double dotGap;
  final int maxChars;
  final bool uppercase;

  const DizzyDotMatrix({
    super.key,
    required this.text,
    this.litColor = DizzyGlow.beam,
    this.dotSize = 3.0,
    this.dotGap = 1.6,
    this.maxChars = 16,
    this.uppercase = true,
  });

  @override
  Widget build(BuildContext context) {
    final shown = (uppercase ? text.toUpperCase() : text);
    final clipped = shown.length > maxChars
        ? shown.substring(0, maxChars)
        : shown;
    final cellW = 5 * (dotSize + dotGap);
    final width = clipped.length * (cellW + dotGap * 3) + 20;
    const height = 7 * 4.6 + 16;
    return Container(
      padding: const EdgeInsets.symmetric(horizontal: 10, vertical: 8),
      decoration: BoxDecoration(
        color: DizzyVoid.obsidian,
        borderRadius: BorderRadius.circular(8),
        border: Border.all(
          color: const Color(0xFFFFFFFF).withValues(alpha: 0.10),
        ),
      ),
      child: RepaintBoundary(
        child: CustomPaint(
          size: Size(width, height),
          painter: _DotMatrixPainter(
            text: clipped,
            lit: litColor,
            dotSize: dotSize,
            dotGap: dotGap,
          ),
        ),
      ),
    );
  }
}

