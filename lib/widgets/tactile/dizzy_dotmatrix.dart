class _DotMatrixPainter extends CustomPainter {
  final String text;
  final Color lit;
  final double dotSize;
  final double dotGap;

  const _DotMatrixPainter({
    required this.text,
    required this.lit,
    required this.dotSize,
    required this.dotGap,
  });

  @override
  void paint(Canvas canvas, Size size) {
    final pitch = dotSize + dotGap;
    final charAdvance = 5 * pitch + dotGap * 3;
    final litPaint = Paint()
      ..style = PaintingStyle.fill
      ..color = lit;
    final litCore = Paint()
      ..style = PaintingStyle.fill
      ..color = const Color(0xFFFFFFFF).withValues(alpha: 0.35);
    final offPaint = Paint()
      ..style = PaintingStyle.fill
      ..color = DizzyVoid.surface2;

    for (int ci = 0; ci < text.length; ci++) {
      final rows = _font5x7[text[ci]] ?? _font5x7[' ']!;
      final baseX = ci * charAdvance;
      for (int row = 0; row < 7; row++) {
        final bits = rows[row];
        for (int col = 0; col < 5; col++) {
          final on = (bits >> (4 - col)) & 1 == 1;
          final cx = baseX + col * pitch + dotSize / 2;
          final cy = row * pitch + dotSize / 2;
          final rect = RRect.fromLTRBR(
            cx - dotSize / 2, cy - dotSize / 2,
            cx + dotSize / 2, cy + dotSize / 2,
            Radius.circular(dotSize / 2),
          );
          canvas.drawRRect(rect, on ? litPaint : offPaint);
          if (on) {
            canvas.drawCircle(
              Offset(cx - dotSize * 0.15, cy - dotSize * 0.15),
              dotSize * 0.22,
              litCore,
            );
          }
        }
      }
    }
  }

  @override
  bool shouldRepaint(covariant _DotMatrixPainter old) =>
      old.text != text ||
      old.lit != lit ||
      old.dotSize != dotSize ||
      old.dotGap != dotGap;
}
